-- P1-5 Spring Session JDBC（会话存 MySQL，不存 Redis）
-- 表名使用 Spring Session 默认的 SPRING_SESSION / SPRING_SESSION_ATTRIBUTES，
-- 应用侧 spring.session.jdbc.initialize-schema=never，迁移由 Flyway 唯一负责。

CREATE TABLE SPRING_SESSION (
  PRIMARY KEY (SESSION_ID),
  SESSION_ID            CHAR(36)     NOT NULL,
  CREATION_TIME         BIGINT       NOT NULL,
  LAST_ACCESS_TIME      BIGINT       NOT NULL,
  MAX_INACTIVE_INTERVAL INT          NOT NULL,
  EXPIRY_TIME           BIGINT       NOT NULL,
  PRINCIPAL_NAME        VARCHAR(100) NULL,
  INDEX SPRING_SESSION_IX1 (SESSION_ID),
  INDEX SPRING_SESSION_IX2 (EXPIRY_TIME),
  INDEX SPRING_SESSION_IX3 (PRINCIPAL_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
  SESSION_ID      CHAR(36)     NOT NULL,
  ATTRIBUTE_NAME  VARCHAR(200) NOT NULL,
  ATTRIBUTE_BYTES BLOB         NOT NULL,
  PRIMARY KEY (SESSION_ID, ATTRIBUTE_NAME),
  INDEX SPRING_SESSION_ATTRIBUTES_IX1 (SESSION_ID),
  CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_ID)
    REFERENCES SPRING_SESSION (SESSION_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
